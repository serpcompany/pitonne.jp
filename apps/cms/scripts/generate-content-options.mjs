import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import matter from "gray-matter"

const dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(dirname, "../../..")
const webContentRoot = path.join(repoRoot, "apps/web/content")
const outputFile = path.join(repoRoot, "apps/cms/src/generated/contentOptions.ts")

function getString(value) {
  return typeof value === "string" && value.trim() ? value.trim() : null
}

function getStringArray(value) {
  return Array.isArray(value) ? value.map(getString).filter(Boolean) : []
}

function readMarkdownFrontmatter(directory) {
  return fs
    .readdirSync(directory)
    .filter((fileName) => fileName.endsWith(".md"))
    .flatMap((fileName) => {
      const absolutePath = path.join(directory, fileName)
      return [matter(fs.readFileSync(absolutePath, "utf8")).data]
    })
}

function readLocalizedFrontmatter(section, locale) {
  const directory = locale === "ja" ? path.join(webContentRoot, section, "ja") : path.join(webContentRoot, section)
  return readMarkdownFrontmatter(directory)
}

function createOption(label, value) {
  return { label, value }
}

const services = {
  en: readLocalizedFrontmatter("services", "en"),
  ja: readLocalizedFrontmatter("services", "ja"),
}

const japaneseServiceLabels = new Map(
  services.ja
    .map((service) => [getString(service.slug), getString(service.title)])
    .filter(([slug, title]) => slug && title),
)

const blogCategoryOptions = services.en
  .filter((service) => getString(service.kind) === "parent")
  .map((service) => {
    const value = getString(service.slug)
    const label = getString(service.title)
    if (!value || !label) {
      return null
    }

    return {
      label,
      labels: {
        en: label,
        ja: japaneseServiceLabels.get(value) ?? label,
      },
      value,
    }
  })
  .filter(Boolean)
  .sort((a, b) => a.label.localeCompare(b.label, "en"))

const relatedServiceSlugOptions = services.en
  .map((service) => {
    const value = getString(service.slug)
    const label = getString(service.title)
    return value && label ? createOption(label, value) : null
  })
  .filter(Boolean)
  .sort((a, b) => a.label.localeCompare(b.label, "en"))

const tags = new Set()
for (const locale of ["en", "ja"]) {
  for (const post of readLocalizedFrontmatter("blog", locale)) {
    for (const tag of getStringArray(post.tags)) {
      tags.add(tag)
    }
  }
}

const blogTagOptions = Array.from(tags)
  .sort((a, b) => a.localeCompare(b, "en"))
  .map((tag) => createOption(tag, tag))

const output = `// Generated by apps/cms/scripts/generate-content-options.mjs from apps/web/content.
// Do not edit by hand.

export const generatedBlogCategoryOptions = ${JSON.stringify(blogCategoryOptions, null, 2)} as const

export const generatedBlogTagOptions = ${JSON.stringify(blogTagOptions, null, 2)} as const

export const generatedRelatedServiceSlugOptions = ${JSON.stringify(relatedServiceSlugOptions, null, 2)} as const
`

fs.writeFileSync(outputFile, output)
console.log(`Wrote ${path.relative(repoRoot, outputFile)}`)
